import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 420, height: 860 }, deviceScaleFactor: 1 });
p.on('pageerror', e => console.log('ERR', e.message));
await p.goto('http://localhost:4173/atomos/'); await p.waitForTimeout(1500);
await p.evaluate(() => window.atomosGallery.focus(33)); await p.waitForTimeout(2500);
await p.screenshot({ path: process.argv[2] + '/loupe-as.png' });
await p.click('#loupe-next'); await p.waitForTimeout(1800);
await p.screenshot({ path: process.argv[2] + '/loupe-se.png' });
await p.click('#loupe-science'); await p.waitForTimeout(600);
await p.screenshot({ path: process.argv[2] + '/loupe-sheet.png' });
await b.close();
