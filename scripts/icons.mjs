// The icon library: every 24×24 SVG in src/icons/ becomes a named icon in the app.
//
//   npm run icons            regenerate src/ui/icons.gen.ts and src/icons/preview.html
//   npm run icons -- --check fail if the generated module is out of date (used by the tests)
//
// `npm run dev` and `npm run build` run this first, so dropping a file in is enough.
// Drawing rules: a 24×24 viewBox, the shape about 20 units tall and centred (2 units of
// padding), any single colour. Black, #000 or any other solid colour is turned into
// currentColor, so icons take the colour of the text around them. White is left alone.
// The file name, lower-case with dashes, is the icon's name: `view-cloud.svg` → 'view-cloud'.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'src', 'icons');
const OUT = join(root, 'src', 'ui', 'icons.gen.ts');
const PREVIEW = join(SRC, 'preview.html');

const COLOUR = /(fill|stroke)="(?!none|currentColor|white|#fff\b|#ffffff\b|url\()([^"]+)"/gi;

function normalise(name, raw) {
  let s = raw.replace(/<\?xml[^>]*>/g, '').replace(/<!--[\s\S]*?-->/g, '').trim();
  const open = s.match(/<svg\b[^>]*>/);
  if (!open) throw new Error(`${name}.svg: no <svg> element`);
  const viewBox = open[0].match(/viewBox="([^"]+)"/)?.[1]?.trim().split(/[\s,]+/).map(Number);
  if (!viewBox || viewBox.join(' ') !== '0 0 24 24') {
    throw new Error(`${name}.svg: viewBox must be "0 0 24 24" (found "${viewBox?.join(' ') ?? 'none'}")`);
  }
  // The root keeps only what every icon needs; size and class are added at use.
  const keep = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin']
    .map((a) => open[0].match(new RegExp(`\\s${a}="[^"]*"`))?.[0] ?? '').join('');
  s = s.replace(open[0], `<svg viewBox="0 0 24 24"${keep}>`);
  s = s.replace(COLOUR, '$1="currentColor"');
  return s.replace(/>\s+</g, '><').replace(/\s{2,}/g, ' ').replace(/\s+\/>/g, '/>');
}

export function build() {
  const files = readdirSync(SRC).filter((f) => f.endsWith('.svg')).sort();
  const icons = files.map((f) => {
    const name = basename(f, '.svg');
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) throw new Error(`${f}: name icons in lower-case-with-dashes`);
    return [name, normalise(name, readFileSync(join(SRC, f), 'utf8'))];
  });
  const body = icons.map(([n, svg]) => `  '${n}': '${svg.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',`).join('\n');
  const module = `// Generated by scripts/icons.mjs from src/icons/*.svg. Do not edit; run \`npm run icons\`.\n\nexport const ICONS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`;
  return { icons, module };
}

function preview(icons) {
  const cell = ([n, svg]) => `<figure><div class="g dark">${svg}${svg}</div><div class="g light">${svg}${svg}</div><figcaption>${n}</figcaption></figure>`;
  return `<!doctype html>
<!-- Generated by scripts/icons.mjs. Open with \`npm run dev\` at /src/icons/preview.html. -->
<meta charset="utf-8"><title>Atomos icons</title>
<style>
body{margin:0;padding:24px;background:#0c0b0a;color:#e2dccf;font:13px system-ui,sans-serif}
h1{font-size:18px;margin:0 0 4px}p{color:#9a9284;margin:0 0 20px}
main{display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:12px}
figure{margin:0;border:1px solid #2a2622;border-radius:8px;overflow:hidden}
.g{display:flex;align-items:center;justify-content:center;gap:16px;padding:14px}
.g svg:first-child{width:24px;height:24px}.g svg:last-child{width:48px;height:48px;outline:1px dashed rgba(127,127,127,.35)}
.dark{color:#e2dccf}.light{background:#dcd5c4;color:#1b1813}
figcaption{padding:6px 10px;font-family:ui-monospace,monospace;color:#9a9284}
</style>
<h1>Atomos icons</h1><p>${icons.length} icons from src/icons/. Each at 24 px and at 48 px with its 24×24 box outlined.</p>
<main>${icons.map(cell).join('')}</main>
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const { icons, module } = build();
  if (process.argv.includes('--check')) {
    const current = (() => { try { return readFileSync(OUT, 'utf8'); } catch { return ''; } })();
    if (current !== module) {
      console.error('src/ui/icons.gen.ts is out of date: run `npm run icons`.');
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, module);
    writeFileSync(PREVIEW, preview(icons));
    console.log(`icons: ${icons.length} written to src/ui/icons.gen.ts`);
  }
}
